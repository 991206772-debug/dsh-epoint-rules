class PromptEnhancer {
    /**
     * 执行提示词强化指令的组装
     * @param {string} originalPrompt 用户输入的原始提示词
     * @returns {string} 注入了核心指令的方法论提示词
     */
    static enhance(originalPrompt) {
        if (!originalPrompt || originalPrompt.trim() === '') {
            return "❌ 错误：请提供需要强化的原始提示词内容。";
        }
        return SYSTEM_INSTRUCTION_TEMPLATE.replace('{{ORIGINAL_PROMPT}}', originalPrompt);
    }
}

module.exports = PromptEnhancer;
